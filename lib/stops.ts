import gtfsStops from "./gtfs-stops";
import stopLinesJson from "../data/stop-lines.json";
import slugify from "../utils/slugify";

/**
 * Stop names were originally taken from the TfGM OData API's `StationLocation` attribute. They're used to build URL
 * slugs and are persisted in visitors' local storage (recently visited stops), so they must not change. Names now come
 * from GTFS data, and these overrides restore the original names wherever GTFS differs.
 */
const legacyStopNames: Partial<Record<string, string>> = {
  "9400ZZMABOB": "Besses O’ Th’ Barn",
  "9400ZZMAGMX": "Deansgate - Castlefield",
  "9400ZZMAFIR": "Firswood",
  "9400ZZMAEVC": "Trafford Palazzo",
  "9400ZZMANEW": "Newton Heath and Moston",
  "9400ZZMASTW": "St Werburgh’s Road",
};

export type StopIdentity = {
  StationLocation: string;
  atcoCode: string;
};

export type StopsEntry = StopIdentity & {
  /** Lines serving this stop, e.g. "Blue Line", "Ashton-Under-Lyne - Bury". Used for search */
  lines: string[];
};

/**
 * Every stop, keyed on the stop-level ATCO code (GTFS uses platform-level codes, e.g. 9400ZZMAHTN1 and 9400ZZMAHTN2,
 * but the TfGM API only accepts the stop-level 9400ZZMAHTN).
 */
export const stopIdentities: StopIdentity[] = (() => {
  const byAtco = new Map<string, StopIdentity>();
  gtfsStops.forEach(({ stop_id, stop_name }) => {
    const atcoCode = stop_id.replace(/\d+$/, "");
    if (!byAtco.has(atcoCode)) {
      const StationLocation = legacyStopNames[atcoCode] ?? stop_name.replace(/ \(Manchester Metrolink\)$/, "");
      byAtco.set(atcoCode, { StationLocation, atcoCode });
    }
  });
  return [...byAtco.values()];
})();

/** Lines per stop, generated by `npm run regenerate-stop-lines` */
const stopLines = stopLinesJson as Partial<Record<string, string[]>>;

/** Every stop, sorted by name, with the lines that serve it */
export const stops: StopsEntry[] = stopIdentities
  .map((stop) => ({ ...stop, lines: stopLines[stop.atcoCode] ?? [] }))
  .sort((a, b) => a.StationLocation.localeCompare(b.StationLocation));

export function findStopByName(stopLocation: string): StopsEntry | undefined {
  return stops.find(({ StationLocation }) => StationLocation === stopLocation);
}

export function findStopBySlug(slug: string): StopsEntry | undefined {
  return stops.find(({ StationLocation }) => slugify(StationLocation) === slug);
}
